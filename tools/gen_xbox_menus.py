#!/usr/bin/env python3
"""
Generates the Xbox menu overrides in misc/uwp/xbox/ui/ from the stock menus
in main/ui/. Run it again after the stock menus change upstream.

The Xbox package ships these files in its xbox/ folder, which the engine
searches before the game's paks, so they replace the stock versions.

It first copies the repo's complete menu set (the Steam paks contain an older
layout that the current UI code and these edits don't match), then changes:
  - Display: removes PC-only options (resolution, aspect ratio, fullscreen,
    v-sync, max FPS). Brightness, black & white, gothic and Show FPS stay.
  - Graphics: the PC presets and the low-level renderer options are replaced
    by one "Mode" choice, Quality (60 FPS) or Performance (120 FPS). The
    engine applies the matching settings itself (see CL_ApplyConsoleGfxMode).
  - Performance tab: removed (the two modes cover it).
  - Sound: removes OpenAL, mute-when-minimized/unfocused and Steam items.
  - View: the screen-blood toggle becomes the Blood option (cg_bloodMode).
  - Graphics: adds a Bloom toggle (xbox_bloom).
  - Controls: key binding pages are replaced by two tabs: Layout (a picture
    of the controller, from tools/gen_controller_layout.py) and Settings
    (look/move sensitivity, aim assist, invert, vibration, auto options).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "main", "ui")
DST = os.path.join(ROOT, "misc", "uwp", "xbox", "ui")

HEADER = ("// Xbox build override of ui/{name}, generated by tools/gen_xbox_menus.py\n"
          "// from main/ui/{name}. Edit the generator, not this file.\n")


def split_items(text):
    """Split a menu fragment into [(kind, chunk)] where kind is 'item' or 'raw'."""
    out = []
    pos = 0
    for m in re.finditer(r'itemDef\s*\{', text):
        if m.start() < pos:
            continue
        depth = 0
        i = m.end() - 1
        while i < len(text):
            c = text[i]
            if c == '/' and text.startswith('//', i):
                i = text.find('\n', i)
                if i < 0:
                    i = len(text)
                continue
            if c == '"':
                i = text.find('"', i + 1) + 1
                continue
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        # take leading whitespace on the itemDef line with the item
        start = text.rfind('\n', 0, m.start()) + 1
        if start < pos:
            start = m.start()
        out.append(('raw', text[pos:start]))
        out.append(('item', text[start:i + 1]))
        pos = i + 1
    out.append(('raw', text[pos:]))
    return out


def field(item, key):
    m = re.search(r'^\s*' + key + r'\s+"([^"]*)"', item, re.M)
    return m.group(1) if m else None


def drop_items(text, pred):
    return ''.join(chunk for kind, chunk in split_items(text)
                   if kind == 'raw' or not pred(chunk))


def keep_first_item_only(text):
    parts = split_items(text)
    out, seen = [], False
    for kind, chunk in parts:
        if kind == 'item':
            if seen:
                continue
            seen = True
        out.append(chunk)
    return ''.join(out)


def mode_items(name, group, x, y):
    style = ('\t\ttextfont UI_FONT_BIG\n\t\ttextalignx 142\n\t\ttextaligny 10\n'
             '\t\ttextscale .22\n\t\tstyle WINDOW_STYLE_FILLED\n'
             '\t\tbackcolor 1 1 1 .07\n\t\tforecolor 1 1 1 1\n\t\tvisible 0\n')
    note = ('\t\ttextfont UI_FONT_BIG\n\t\ttextalignx 4\n\t\ttextaligny 10\n'
            '\t\ttextscale .18\n\t\tforecolor 1 1 1 .7\n\t\tvisible 0\n\t\tdecoration\n')
    return f'''
	itemDef {{
		name {name}
		group {group}
		type ITEM_TYPE_MULTI
		text "Mode"
		cvar "xbox_gfxMode"
		cvarFloatList {{ "Quality - 60 FPS" 0 "Performance - 120 FPS" 1 }}
		rect {x} {y} 290 12
		textalign ITEM_ALIGN_RIGHT
{style}	}}

	itemDef {{
		name {name}
		group {group}
		type ITEM_TYPE_YESNO
		text "Bloom"
		cvar "xbox_bloom"
		rect {x} {y + 15} 290 12
		textalign ITEM_ALIGN_RIGHT
{style}	}}

	itemDef {{
		name {name}
		group {group}
		type ITEM_TYPE_YESNO
		text "Ragdolls"
		cvar "cg_ragdoll"
		rect {x} {y + 30} 290 12
		textalign ITEM_ALIGN_RIGHT
{style}	}}

	itemDef {{
		name {name}
		group {group}
		type ITEM_TYPE_TEXT
		text "Quality: HD textures and full effects, capped at 60 FPS."
		rect {x} {y + 55} 290 12
		textalign ITEM_ALIGN_LEFT
{note}	}}

	itemDef {{
		name {name}
		group {group}
		type ITEM_TYPE_TEXT
		text "Performance: up to 120 FPS (switches a 120 Hz TV to 120 Hz)."
		rect {x} {y + 70} 290 12
		textalign ITEM_ALIGN_LEFT
{note}	}}
'''


def blood_option(text):
    pat = re.compile(r'type ITEM_TYPE_YESNO\s*\n(\s*)text "@HUD_BLOOD"\s*\n\s*cvar "cg_bloodBlend"')
    m = pat.search(text)
    if not m:
        raise SystemExit("blood item not found")
    ind = m.group(1)
    text = drop_items(text, lambda it: field(it, "text") in DROP_TEXT)
    m = pat.search(text)
    return text[:m.start()] + ('type ITEM_TYPE_MULTI\n' + ind + 'text "Blood:"\n' + ind +
                               'cvar "cg_bloodMode"\n' + ind +
                               'cvarFloatList { "Default" 0 "Green" 1 "Disabled" 2 "Extreme" 3 }') + text[m.end():]


DISPLAY_DROP = {"r_mode", "cg_fixedaspect", "r_fullscreen", "r_swapinterval", "com_maxfps"}
DROP_TEXT = {"@SYSTEM_SOCIALS", "@SYSTEM_APPLY"}   # PC social links; Apply (Xbox applies settings itself)


def repack_rows(text):
    """Close the gaps left by removed options: option rows (290x12) are
    re-spaced in order, headings get a little extra room."""
    out, newy, mapping, last_dec = [], None, {}, None
    for kind, chunk in split_items(text):
        m = re.search(r'\brect\s+([\d.]+)\s+([\d.]+)\s+290\s+12', chunk) if kind == 'item' else None
        if m:
            oldy = m.group(2)
            dec = 'decoration' in chunk and 'cvar' not in chunk
            if oldy not in mapping:
                if newy is None:
                    newy = float(oldy)
                else:
                    newy += 22 if (dec or last_dec) else 16
                mapping[oldy] = newy
                last_dec = dec
            y = mapping[oldy]
            chunk = chunk[:m.start(2)] + ('%g' % y) + chunk[m.end(2):]
        out.append(chunk)
    return ''.join(out)
SOUND_DROP = {"s_useOpenAL", "s_muteWhenMinimized", "s_muteWhenUnfocused"}


def gen(name, transform):
    with open(os.path.join(SRC, name), encoding="latin-1") as f:
        text = f.read()
    text = transform(text)
    os.makedirs(DST, exist_ok=True)
    with open(os.path.join(DST, name), "w", encoding="latin-1") as f:
        f.write(HEADER.format(name=name) + text)
    print("wrote", name)


def copy_stock_ui():
    """The installed Steam paks carry an older, monolithic set of menus that
    don't match this source tree (or its compiled UI module). Ship the repo's
    whole menu set in the overlay so menus and code always match."""
    os.makedirs(DST, exist_ok=True)
    for name in sorted(os.listdir(SRC)):
        if name.endswith(".menu") or name in ("menus.txt", "menudef.h"):
            with open(os.path.join(SRC, name), "rb") as f:
                data = f.read()
            with open(os.path.join(DST, name), "wb") as f:
                f.write(data)


# ---------------------------------------------------------------------------
# Controls: Layout + Settings tabs
# ---------------------------------------------------------------------------
def nth_item(text, n):
    return [c for k, c in split_items(text) if k == 'item'][n]


def retab(item, label, width=64):
    item = re.sub(r'text "[^"]*"', f'text "{label}"', item, count=1)
    item = re.sub(r'(\brect\s+[\d.]+\s+[\d.]+\s+)[\d.]+', lambda m: m.group(1) + str(width), item, count=1)
    item = re.sub(r'textalignx\s+[\d.]+', f'textalignx {width // 2}', item, count=1)
    return item


def find_item(text, cvar):
    for k, c in split_items(text):
        if k == 'item' and cvar in (field(c, 'cvar'), field(c, 'cvarfloat')):
            return c
    raise SystemExit("control item not found: " + cvar)


def place(item, name, x, y):
    item = re.sub(r'^(\s*)name\s+\S+', lambda m: m.group(1) + 'name ' + name, item, count=1, flags=re.M)
    return re.sub(r'\brect\s+[\d.]+\s+[\d.]+\s+290\s+12', f'rect {x} {y} 290 12', item, count=1)


def controls_set(prefix, group, img_rect, x, y0, header_note):
    look = open(os.path.join(SRC, prefix + "look.menu"), encoding="latin-1").read()
    misc = open(os.path.join(SRC, prefix + "misc.menu"), encoding="latin-1").read()
    move = open(os.path.join(SRC, prefix + "move.menu"), encoding="latin-1").read()

    # Layout tab = the old Look tab button + the picture
    items = split_items(look)
    head = items[0][1]
    keep = [retab(nth_item(look, 0), "Layout")]
    if prefix.startswith("main"):
        keep.append(nth_item(look, 1))      # the "CONTROLS" title
    ix, iy, iw, ih = img_rect
    picture = f'''
	itemDef {{
		name look
		group {group}
		style WINDOW_STYLE_SHADER
		background "ui/xbox_controller"
		rect {ix} {iy} {iw} {ih}
		forecolor 1 1 1 1
		visible 0
		decoration
	}}
'''
    out_look = head + "\n".join(keep) + picture

    # Settings tab = the old Move tab button + gamepad options
    rows = [find_item(look, c) for c in ("j_lookSens", "j_moveSens", "j_aimassist", "j_invertLook")]
    vib = find_item(look, "j_invertLook")
    vib = re.sub(r'text "[^"]*"', 'text "Vibration"', vib, count=1)
    vib = vib.replace('cvar "j_invertLook"', 'cvar "xbox_vibration"')
    rows.append(vib)
    sens = find_item(look, "j_lookSens")
    ads = re.sub(r'text "[^"]*"', 'text "Aim Down Sights Sensitivity"', sens, count=1)
    ads = re.sub(r'cvarfloat\s+"j_lookSens"[^\n]*', 'cvarfloat "j_adsSens" 0.75 0.3 1.5', ads)
    curve = re.sub(r'text "[^"]*"', 'text "Look Precision Curve"', sens, count=1)
    curve = re.sub(r'cvarfloat\s+"j_lookSens"[^\n]*', 'cvarfloat "j_lookCurve" 1.6 1.0 3.0', curve)
    qt = find_item(look, "j_invertLook")
    qt = re.sub(r'text "[^"]*"', 'text "Quick Turn"', qt, count=1)
    qt = qt.replace('cvar "j_invertLook"', 'cvar "j_quickTurn"')
    rows.insert(1, ads)
    rows.insert(2, curve)
    rows.append(qt)
    for label, cv in (("Toggle Crouch", "xbox_crouchToggle"), ("Toggle Sprint", "xbox_sprintToggle"),
                      ("Hold to Aim", "xbox_aimHold")):
        it = find_item(look, "j_invertLook")
        it = re.sub(r'text "[^"]*"', f'text "{label}"', it, count=1)
        rows.append(it.replace('cvar "j_invertLook"', f'cvar "{cv}"'))
    rows += [find_item(misc, c) for c in ("cg_autoreload", "cg_autoactivate", "cg_autoswitch")]
    step = 18 if header_note else 14     # the in-game window is shorter
    placed = [place(r, "move", x, y0 + step * i) for i, r in enumerate(rows)]
    out_move = split_items(move)[0][1] + retab(nth_item(move, 0), "Settings") + "\n" + "\n".join(placed) + "\n"

    empty = "// Key bindings are fixed on Xbox; see the Layout tab.\n"
    return {prefix + "look.menu": out_look, prefix + "move.menu": out_move,
            prefix + "shoot.menu": empty, prefix + "misc.menu": empty}


def write_raw(name, text):
    with open(os.path.join(DST, name), "w", encoding="latin-1") as f:
        f.write(HEADER.format(name=name) + text)
    print("wrote", name)


def main():
    copy_stock_ui()
    # Display
    for n in ("main_system_display.menu", "ingame_system_graphics.menu"):
        gen(n, lambda t: repack_rows(drop_items(t, lambda it: field(it, "cvar") in DISPLAY_DROP
                                                or field(it, "text") in DROP_TEXT)))
    # Graphics -> Mode
    gen("main_system_graphics.menu",
        lambda t: keep_first_item_only(t) + mode_items("iortcwgraphics", "system", 300, 140))
    gen("ingame_system_iortcw.menu",
        lambda t: keep_first_item_only(t) + mode_items("iortcwgraphics", "grpsystem", 82, 40))
    # Performance tab: gone
    for n in ("main_system_performance.menu", "ingame_system_performance.menu"):
        gen(n, lambda t: "// Performance settings are covered by Graphics > Mode on Xbox.\n")
    # Sound
    def sound(t):
        t = drop_items(t, lambda it: field(it, "cvar") in SOUND_DROP)
        return drop_items(t, lambda it: (field(it, "text") or "").startswith("@STEAM"))
    for n in ("main_system_sound_steam.menu", "ingame_system_sound.menu"):
        gen(n, sound)
    # Blood option
    for n in ("main_game_view.menu", "ingame_options_view.menu"):
        gen(n, blood_option)
    # Controls
    files = controls_set("main_controls_", "controls", (226, 128, 431, 216), 300, 132, True)
    files.update(controls_set("ingame_controls_", "grpControls", (6, 28, 431, 216), 82, 32, False))
    files["main_controls_shoot_advanced.menu"] = "// Key bindings are fixed on Xbox; see the Layout tab.\n"
    for n, t in files.items():
        write_raw(n, t)
    # copy_stock_ui() above restores the stock campaign_menu.menu; rebuild the
    # Xbox campaign flow on top of it every time so it can't be lost.
    import gen_xbox_campaign
    gen_xbox_campaign.main()


if __name__ == "__main__":
    sys.exit(main())
