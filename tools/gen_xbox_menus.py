def cheats_button(t):
    """A CHEATS entry under Quit in the in-game menu."""
    item = text_button("xbcheats", "CHEATS", 375, "open ingame_cheats", True)
    item += text_button("xbachievements", "ACHIEVEMENTS", 404, "open ingame_achievements")
    i = t.index("name quit")
    j = t.index("}", t.index("mouseExit", i)) + 1      # end of its mouseExit { }
    j = t.index("}", j) + 1                             # end of the quit item
    t = t[:j] + "\n" + item + t[j:]
    # descriptions beside the buttons rather than under them (where they ran
    # into CHEATS / ACHIEVEMENTS); see tools/gen_ingame_desc.py. Same names
    # as the highlight pictures, so the buttons' show/hide covers them too.
    descs = ""
    for n, y in (("save", 144), ("load", 177), ("controls", 210), ("game", 243),
                 ("system", 276), ("main", 309), ("quit", 342)):
        descs += f'''
	itemDef
	{{
		name realrtcw_ingame_{n}
		style WINDOW_STYLE_SHADER
		rect 245 {y + 6} 224 14
		background "ui/assets/xbox_desc_{n}.tga"
		visible 1
		decoration
	}}
'''
    i = t.index("name save")
    i = t.rindex("itemDef", 0, i)
    t = t[:i] + descs + "\n\t" + t[i:]
    k = t.rindex("}")                                   # the file's outer brace
    menus = cheat_menus()
    menus += achievements_menu("ingame_achievements", "close ingame_achievements ; open ingame")
    menus += achievements_menu("xbox_achievements", "close xbox_achievements")
    return t[:k] + menus + "\n" + t[k:]


def main():
    copy_stock_ui()
    gen("ingame.menu", cheats_button)
    gen("main_buttons.menu", main_buttons)
    # Display
    for n in ("main_system_display.menu", "ingame_system_graphics.menu"):
        gen(n, lambda t: repack_rows(drop_items(t, lambda it: field(it, "cvar") in DISPLAY_DROP
                                                or field(it, "text") in DROP_TEXT)))
    # Graphics -> Mode
    gen("main_system_graphics.menu",
        lambda t: keep_first_item_only(t) + mode_items("iortcwgraphics", "system", 300, 140))
    gen("ingame_system_iortcw.menu",
        lambda t: keep_first_item_only(t) + mode_items("iortcwgraphics", "grpsystem", 82, 40))
    # Performance tab: gone
    for n in ("main_system_performance.menu", "ingame_system_performance.menu"):
        gen(n, lambda t: "// Performance settings are covered by Graphics > Mode on Xbox.\n")
    # Sound
    def sound(t):
        t = drop_items(t, lambda it: field(it, "cvar") in SOUND_DROP)
        return drop_items(t, lambda it: (field(it, "text") or "").startswith("@STEAM"))
    for n in ("main_system_sound_steam.menu", "ingame_system_sound.menu"):
        gen(n, sound)
    # Blood option
    for n in ("main_game_view.menu", "ingame_options_view.menu"):
        gen(n, blood_option)
    # Controls
    files = controls_set("main_controls_", "controls", (226, 128, 431, 216), 300, 132, True)
    files.update(controls_set("ingame_controls_", "grpControls", (6, 28, 431, 216), 82, 32, False))
    files["main_controls_shoot_advanced.menu"] = "// Key bindings are fixed on Xbox; see the Layout tab.\n"
    for n, t in files.items():
        write_raw(n, t)
    # copy_stock_ui() above restores the stock campaign_menu.menu; rebuild the
    # Xbox campaign flow on top of it every time so it can't be lost.
    import gen_xbox_campaign
    gen_xbox_campaign.main()


if __name__ == "__main__":
    sys.exit(main())
