#!/usr/bin/env python3
"""
Generates the Xbox menu overrides in misc/uwp/xbox/ui/ from the stock menus
in main/ui/. Run it again after the stock menus change upstream.

The Xbox package ships these files in its xbox/ folder, which the engine
searches before the game's paks, so they replace the stock versions.

It first copies the repo's complete menu set (the Steam paks contain an older
layout that the current UI code and these edits don't match), then changes:
  - Display: removes PC-only options (resolution, aspect ratio, fullscreen,
    v-sync, max FPS). Brightness, black & white, gothic and Show FPS stay.
  - Graphics: the PC presets and the low-level renderer options are replaced
    by one "Mode" choice, Quality (60 FPS) or Performance (120 FPS). The
    engine applies the matching settings itself (see CL_ApplyConsoleGfxMode).
  - Performance tab: removed (the two modes cover it).
  - Sound: removes OpenAL, mute-when-minimized/unfocused and Steam items.
  - View: the screen-blood toggle becomes the Blood option (cg_bloodMode).
  - Graphics: adds a Bloom toggle (xbox_bloom).
  - Controls: key binding pages are replaced by two tabs: Layout (a picture
    of the controller, from tools/gen_controller_layout.py) and Settings
    (look/move sensitivity, aim assist, invert, vibration, auto options).
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "main", "ui")
DST = os.path.join(ROOT, "misc", "uwp", "xbox", "ui")

HEADER = ("// Xbox build override of ui/{name}, generated by tools/gen_xbox_menus.py\n"
          "// from main/ui/{name}. Edit the generator, not this file.\n")


def split_items(text):
    """Split a menu fragment into [(kind, chunk)] where kind is 'item' or 'raw'."""
    out = []
    pos = 0
    for m in re.finditer(r'itemDef\s*\{', text):
        if m.start() < pos:
            continue
        depth = 0
        i = m.end() - 1
        while i < len(text):
            c = text[i]
            if c == '/' and text.startswith('//', i):
                i = text.find('\n', i)
                if i < 0:
                    i = len(text)
                continue
            if c == '"':
                i = text.find('"', i + 1) + 1
                continue
            if c == '{':
                depth += 1
            elif c == '}':
                depth -= 1
                if depth == 0:
                    break
            i += 1
        # take leading whitespace on the itemDef line with the item
        start = text.rfind('\n', 0, m.start()) + 1
        if start < pos:
            start = m.start()
        out.append(('raw', text[pos:start]))
        out.append(('item', text[start:i + 1]))
        pos = i + 1
    out.append(('raw', text[pos:]))
    return out


def field(item, key):
    m = re.search(r'^\s*' + key + r'\s+"([^"]*)"', item, re.M)
    return m.group(1) if m else None


def drop_items(text, pred):
    return ''.join(chunk for kind, chunk in split_items(text)
                   if kind == 'raw' or not pred(chunk))


def keep_first_item_only(text):
    parts = split_items(text)
    out, seen = [], False
    for kind, chunk in parts:
        if kind == 'item':
            if seen:
                continue
            seen = True
        out.append(chunk)
    return ''.join(out)


